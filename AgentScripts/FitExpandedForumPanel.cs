var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
if(UnityEditor.EditorApplication.isPlayingOrWillChangePlaymode || scene.path != "Assets/Scenes/Explore_Proto.unity") throw new System.InvalidOperationException("Explore_Proto edit mode required.");
var m = System.Linq.Enumerable.Single(System.Linq.Enumerable.SelectMany(scene.GetRootGameObjects(), r => r.GetComponentsInChildren<ExploreProtoMessenger>(true)));
var p = m.forumArticlePage;
var panel = (UnityEngine.RectTransform)m.siteDetailPanel.transform;
var scrollRect = (UnityEngine.RectTransform)p.scroll.transform;
var background = (UnityEngine.RectTransform)p.page.Find("PageBackground");
if(!background || scrollRect.parent != panel || p.forumContent.parent != p.scroll.viewport) throw new System.InvalidOperationException("Unexpected forum hierarchy.");
UnityEditor.Undo.IncrementCurrentGroup(); int group = UnityEditor.Undo.GetCurrentGroup();
UnityEditor.Undo.SetCurrentGroupName("Fit forum contents to expanded article panel");
UnityEditor.Undo.RecordObject(scrollRect,"Fill expanded article panel");
scrollRect.anchorMin = UnityEngine.Vector2.zero; scrollRect.anchorMax = UnityEngine.Vector2.one;
scrollRect.offsetMin = scrollRect.offsetMax = UnityEngine.Vector2.zero;
UnityEditor.Undo.RecordObject(p.scroll.viewport,"Fill article viewport");
p.scroll.viewport.anchorMin = UnityEngine.Vector2.zero; p.scroll.viewport.anchorMax = UnityEngine.Vector2.one;
p.scroll.viewport.offsetMin = p.scroll.viewport.offsetMax = UnityEngine.Vector2.zero;
UnityEditor.Undo.RecordObject(p.forumContent,"Remove obsolete horizontal content offsets");
float documentHeight = p.forumContent.rect.height;
p.forumContent.anchorMin = new UnityEngine.Vector2(0,1); p.forumContent.anchorMax = UnityEngine.Vector2.one;
p.forumContent.pivot = new UnityEngine.Vector2(0,1);
p.forumContent.sizeDelta = new UnityEngine.Vector2(0,documentHeight);
p.forumContent.anchoredPosition = UnityEngine.Vector2.zero;
UnityEditor.Undo.RecordObject(p,"Extend page background across article viewport");
var backgrounds = new System.Collections.Generic.List<UnityEngine.RectTransform>(p.fullWidthBackgrounds);
if(!backgrounds.Contains(background)) backgrounds.Add(background);
p.fullWidthBackgrounds = backgrounds.ToArray();
float width = panel.rect.width;
float margin = UnityEngine.Mathf.Max(0,(width-p.page.rect.width)*.5f);
UnityEditor.Undo.RecordObject(p.page,"Center fixed size forum in expanded viewport");
var position = p.page.anchoredPosition; position.x = margin; p.page.anchoredPosition = position;
foreach(var r in p.fullWidthBackgrounds) {
 UnityEditor.Undo.RecordObject(r,"Extend background to expanded panel edges");
 r.SetSizeWithCurrentAnchors(UnityEngine.RectTransform.Axis.Horizontal,width);
 var offset = r.anchoredPosition; offset.x = -margin; r.anchoredPosition = offset;
}
UnityEditor.EditorUtility.SetDirty(p);
UnityEditor.Undo.CollapseUndoOperations(group);
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
return "Saved inner scroll/viewport alignment to existing expanded panel (width "+width+"); normalized ForumContent width offsets; centered fixed document and full-width backgrounds. Parent panel preserved.";
